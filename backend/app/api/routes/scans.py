import time
from typing import List, Optional
from fastapi import APIRouter, HTTPException, Query, status
from app.schemas.detection import (
    PredictionResponse,
    ScanSummary,
    StatsResponse,
    ReportResponse,
)
from app.storage.repository import scan_repository

router = APIRouter(tags=["Scans & Reports"])


@router.get("/scans", response_model=List[PredictionResponse])
def list_scans(
    limit: int = Query(50, ge=1, le=200),
    offset: int = Query(0, ge=0),
) -> List[PredictionResponse]:
    """Retrieves all past analyzed sonar scans sorted newest first."""
    return scan_repository.list_all(limit=limit, offset=offset)


@router.get("/scans/{scan_id}", response_model=PredictionResponse)
def get_scan(scan_id: str) -> PredictionResponse:
    """Retrieves detailed detection result for a specific scan ID."""
    scan = scan_repository.get(scan_id)
    if not scan:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Scan with ID '{scan_id}' not found.",
        )
    return scan


@router.delete("/scans/{scan_id}", status_code=status.HTTP_200_OK)
def delete_scan(scan_id: str):
    """Deletes a scan from the repository."""
    deleted = scan_repository.delete(scan_id)
    if not deleted:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Scan with ID '{scan_id}' not found.",
        )
    return {"status": "success", "message": f"Scan '{scan_id}' deleted."}


@router.get("/stats", response_model=StatsResponse)
def get_statistics() -> StatsResponse:
    """Computes real aggregate metrics across all processed sonar scans."""
    return scan_repository.get_stats()


@router.get("/scans/{scan_id}/report", response_model=ReportResponse)
def generate_scan_report(scan_id: str) -> ReportResponse:
    """
    Generates a structured marine intelligence inspection report for a given scan.
    Clearly distinguishes AI-detected candidates from confirmed ground truth.
    """
    scan = scan_repository.get(scan_id)
    if not scan:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Scan with ID '{scan_id}' not found.",
        )

    total = scan.total_detections
    pipeline = getattr(scan, "pipeline", "debris")
    filtered_count = getattr(scan, "clutter_filtered_count", 0)

    if total == 0:
        analyst_summary = (
            f"Side-scan sonar track '{scan.filename}' was processed via the {pipeline.upper()} pipeline "
            f"at confidence threshold {scan.confidence_threshold:.2f}. No significant anthropogenic debris "
            f"or underwater anomalies were detected above threshold. The seafloor area appears clear of major obstructions."
        )
    else:
        types_list = [d.type for d in scan.detections]
        types_str = ", ".join(sorted(list(set(types_list))))
        analyst_summary = (
            f"AI-assisted sonar inspection identified {total} potential target candidate(s) in '{scan.filename}' "
            f"using the {pipeline.upper()} detection pipeline. Identified categories: [{types_str}]. "
            f"Highest candidate confidence: {scan.highest_confidence * 100:.1f}%. "
            f"Inference latency: {scan.inference_ms:.1f} ms. "
            f"Acoustic clutter filter rejected {filtered_count} background speckle/artifact candidate(s)."
        )

    clutter_summary = (
        f"Acoustic clutter filtering evaluated all raw candidate bounding boxes: "
        f"{filtered_count} natural sediment/nadir edge artifact(s) were successfully suppressed. "
        f"{total} candidate(s) met physical aspect-ratio and acoustic shadow criteria."
    )

    disclaimer = (
        "CONFIDENTIALITY & SCIENTIFIC NOTICE: Detections generated by this system represent "
        "AI-detected candidates derived from side-scan sonar acoustic backscatter. Final confirmation of "
        "marine debris, derelict gear, or seabed anomalies requires human diver, ROV, or field verification."
    )

    return ReportResponse(
        scan=scan,
        generated_at=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        analyst_summary=analyst_summary,
        clutter_filtering_summary=clutter_summary,
        disclaimer=disclaimer,
        metrics={
            "total_detections": total,
            "pipeline": pipeline,
            "clutter_filtered_count": filtered_count,
            "highest_confidence": scan.highest_confidence,
            "inference_ms": scan.inference_ms,
            "has_geolocation": scan.location.latitude is not None
            and scan.location.longitude is not None,
            "verification_status": getattr(scan, "verification_status", "ai_candidate"),
        },
    )
